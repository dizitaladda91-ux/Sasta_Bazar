-- Blog Portal Schema for Sasta Bazaar
-- Uses blog_categories so it does not collide with the e-commerce categories table.

CREATE TABLE IF NOT EXISTS blog_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  excerpt TEXT NOT NULL DEFAULT '',
  content_html TEXT NOT NULL DEFAULT '',
  featured_image TEXT NOT NULL DEFAULT '',
  featured_image_alt TEXT NOT NULL DEFAULT '',
  featured_image_width INTEGER NOT NULL DEFAULT 1200,
  featured_image_height INTEGER NOT NULL DEFAULT 675,
  category_id BIGINT REFERENCES blog_categories(id) ON DELETE SET NULL,
  author_name TEXT NOT NULL DEFAULT 'Sasta Bazaar Editorial',
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'scheduled')),
  published_at TIMESTAMPTZ,
  focus_keyword TEXT NOT NULL DEFAULT '',
  meta_title TEXT NOT NULL DEFAULT '',
  meta_description TEXT NOT NULL DEFAULT '',
  canonical_url TEXT NOT NULL DEFAULT '',
  og_image TEXT NOT NULL DEFAULT '',
  noindex BOOLEAN NOT NULL DEFAULT FALSE,
  reading_time INTEGER NOT NULL DEFAULT 1,
  word_count INTEGER NOT NULL DEFAULT 0,
  seo_score INTEGER NOT NULL DEFAULT 0,
  schema_type TEXT NOT NULL DEFAULT 'BlogPosting',
  custom_schema TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE posts ADD COLUMN IF NOT EXISTS schema_type TEXT NOT NULL DEFAULT 'BlogPosting';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS custom_schema TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS posts_status_published_idx ON posts(status, published_at DESC);
CREATE INDEX IF NOT EXISTS posts_category_idx ON posts(category_id);

CREATE TABLE IF NOT EXISTS tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS post_tags (
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, tag_id)
);

CREATE TABLE IF NOT EXISTS post_faqs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS post_faqs_post_idx ON post_faqs(post_id, sort_order);

CREATE TABLE IF NOT EXISTS post_products (
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (post_id, product_id)
);

CREATE TABLE IF NOT EXISTS redirects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  old_slug TEXT NOT NULL UNIQUE,
  new_slug TEXT NOT NULL,
  status_code INTEGER NOT NULL DEFAULT 301,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS redirects_old_slug_idx ON redirects(old_slug);
